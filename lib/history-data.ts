export interface HistoryItem {
  id: string;
  type: "video" | "short";
  /** YouTube id */
  videoId: string;
  title: string;
  channel: string;
  channelId: string;
  channelAvatar: string;
  thumbnail: string;
  duration: string;
  views: string;
  timeAgo: string;
  /** Epoch ms of when it was watched */
  watchedDate: number;
}

export function historySeed(): HistoryItem[] {
  return allHistoryData.map((v) => ({
    id: v.id,
    type: v.type === "short" ? "short" : "video",
    videoId: v.videoId,
    title: v.title,
    channel: v.channel,
    channelId: v.channelId,
    channelAvatar: v.channelAvatar,
    thumbnail: v.thumbnail,
    duration: v.duration,
    views: v.views,
    timeAgo: v.timeAgo,
    watchedDate: new Date(v.watchedDate).getTime(),
  }));
}
